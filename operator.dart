void main() {
  // Example 1 (Operator aritmatika)
  int num1 = 10;
  int num2 = 3;

  int tambah = num1 + num2;
  int kurang = num1 - num2;
  int kali = num1 * num2;
  double bagi = num1 / num2;

  print("Pertambahan   = $tambah.");
  print("Pengurangan   = $kurang.");
  print("Perkalian     = $kali.");
  print("Pembagian     = $bagi.");

  //Example 2 (Operator relasi)
  int angka1 = 10;
  int angka2 = 5;

  print(angka1 == angka2);
  print(angka1 < angka2);
  print(angka1 > angka2);
  print(angka1 <= angka2);
  print(angka1 >= angka2);
}
